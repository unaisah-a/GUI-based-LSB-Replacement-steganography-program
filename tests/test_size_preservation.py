PAYLOAD = b"A payload whose presence must not have to change the file's length." * 3

_RESULTS: list[dict[str, Any]] = []


def record(result: SizeResult, scenario: str) -> None:
    row = result.as_dict()
    row["scenario"] = scenario
    _RESULTS.append(row)


@pytest.fixture(scope="module", autouse=True)
def write_evidence():
    """Write the experiment's artefacts once every case in this file has run."""
    _RESULTS.clear()
    yield

    if not _RESULTS:  # pragma: no cover - only when the module is deselected
        return

    directory = Path(__file__).resolve().parents[1] / "evidence" / "results"
    directory.mkdir(parents=True, exist_ok=True)

    applicable = [row for row in _RESULTS if row["applicable"]]
    matched = [row for row in applicable if row["exact"]]
    attempted = [row for row in _RESULTS if row["attempted"]]
    attempted_and_matched = [row for row in attempted if row["exact"]]

    file_utils.write_json_atomic(
        str(directory / "size_preservation.json"),
        {
            "experiment": "exact file-size preservation",
            "total": len(_RESULTS),
            "applicable": len(applicable),
            "exact": len(matched),
            "attempts": len(attempted),
            "attempts_that_matched": len(attempted_and_matched),
            "cases": _RESULTS,
        },
        overwrite=True,
    )

    lines = [
        "# File-Size Preservation Experiment",
        "",
        "Generated by `tests/test_size_preservation.py`. Every row is one measured "
        "case, not a claim.",
        "",
        "## What was asked",
        "",
        "Investigate whether a stego file can be made exactly the same size as its "
        "cover, and record when it succeeds and when it does not. The plan is "
        "explicit that this must not be claimed in general unless testing proves it, "
        "so the failures below are part of the result rather than omissions from it.",
        "",
        "## Answer, by container",
        "",
        "| Container | Exact size? | Why |",
        "|---|---|---|",
        "| WAV (PCM 16) | always | Samples are stored literally at fixed width, so "
        "replacing low bits changes values and not counts. |",
        "| BMP | always | Same reason: uncompressed, fixed-stride pixel storage. |",
        "| PNG | depends on the image | The pixel data is DEFLATE-compressed, so the "
        "answer is a property of the individual image rather than of the format. Three "
        "outcomes were measured; see below. |",
        "| MKV (FFV1) | not applicable | A protected clip is re-encoded from decoded "
        "frames, so its size reflects the codec, not the payload. |",
        "",
        "### The three PNG outcomes, measured",
        "",
        "1. **Free.** A cover that is already incompressible (photographic noise) is "
        "stored rather than compressed, so every DEFLATE level produces the same "
        "length and the stego file comes out at the cover's size with nothing done. "
        "This is the best case and needs no padding chunk, so it leaves no trace.",
        "2. **Matched by padding.** When the best of the ten candidate encodings lands "
        "*under* the cover's length, the shortfall is closed exactly with an ancillary "
        "chunk. Observed for a two-value cover at depth 8, where replacing whole low "
        "bytes made the pixel data more compressible than the cover's.",
        "3. **Impossible.** When every candidate is already *larger* than the cover — "
        "the usual case for a smooth or flat image, because LSB replacement pushes low "
        "bits toward random and random data does not compress — the size cannot be "
        "matched at all. Bytes cannot be removed from a PNG without changing its "
        "pixels.",
        "",
        "## Measured cases",
        "",
        f"- cases measured: {len(_RESULTS)}",
        f"- cases where the question applies: {len(applicable)}",
        f"- of those, exactly the cover's size: {len(matched)}",
        f"- PNG matching attempts: {len(attempted)}, of which "
        f"{len(attempted_and_matched)} succeeded",
        "",
        "| Scenario | Container | Cover | Stego | Final | Difference | Exact | "
        "Strategy |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for row in _RESULTS:
        if not row["applicable"]:
            exact = "n/a"
        else:
            exact = "yes" if row["exact"] else "no"
        lines.append(
            f"| {row['scenario']} | {row['container']} | {row['cover_size']:,} | "
            f"{row['stego_size']:,} | {row['final_size']:,} | "
            f"{row['difference']:+,} | {exact} | {row['strategy']} |"
        )

    lines += [
        "",
        "## The PNG strategy in full",
        "",
        "1. Re-encode the stego pixels at every DEFLATE level from 0 to 9. The levels "
        "produce different lengths, so one may already equal the cover's. No pixel "
        "changes.",
        "2. If the smallest candidate is still short of the target, insert an "
        f"ancillary `{PADDING_CHUNK_TYPE.decode()}` chunk sized to close the gap "
        "exactly. Ancillary chunks are skippable by specification, so the pixels "
        "still decode identically.",
        "",
        "### Where it stops working",
        "",
        f"- If every candidate is already **larger** than the cover, the size cannot "
        f"be matched. Bytes cannot be removed from a PNG without changing its "
        f"pixels. This is the usual case at higher LSB depths, and it is the reason "
        f"exact PNG preservation is reported per file rather than promised.",
        f"- If the shortfall is smaller than {MIN_PNG_CHUNK_OVERHEAD} bytes, it cannot "
        f"be padded either: that is what a PNG chunk costs with an empty payload.",
        "",
        "### A cost worth naming",
        "",
        "A padding chunk is an unusual feature in an otherwise plain PNG. A file "
        "padded to match its cover's size may therefore be *more* conspicuous to an "
        "analyst than one that is simply the wrong size. Matching the size is not "
        "automatically the better choice.",
        "",
    ]
    file_utils.write_text_atomic(
        str(directory / "size_preservation.md"), "\n".join(lines), overwrite=True
    )


