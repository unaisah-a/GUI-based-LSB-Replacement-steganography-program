class TestVideo:
    def test_video_is_reported_as_not_applicable(self, mkv_cover, tmp_path):
        stego = str(tmp_path / "stego.mkv")
        video_stego.embed_video(mkv_cover, stego, PAYLOAD, 2, 0)

        result = size_preservation.size_outcome(mkv_cover, stego)
        record(result, "MKV (FFV1), depth 2")

        assert result.applicable is False
        assert result.attempted is False
        assert result.inherent is False
        assert "not applicable" in result.strategy
        assert any("re-encoded" in note for note in result.notes)
        assert "does not apply" in result.summary()

    def test_a_coincidental_size_match_is_not_counted_as_preservation(
        self, mkv_cover, tmp_path
    ):
        """Two separate FFV1 encodings can land on the same length by chance.

        Recording that as a success would be the most tempting way to overstate this
        experiment's result, so the coincidence is called out explicitly when it
        happens rather than tallied.
        """
        stego = str(tmp_path / "stego.mkv")
        video_stego.embed_video(mkv_cover, stego, PAYLOAD, 2, 0)

        result = size_preservation.size_outcome(mkv_cover, stego)
        if result.stego_size == result.cover_size:
            assert any("coincidence" in note for note in result.notes)
        assert result.applicable is False
