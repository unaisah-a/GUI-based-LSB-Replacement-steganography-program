class TestDeflateLevels:
    def test_every_level_encodes_the_same_pixels(self, png_cover, tmp_path):
        """The size varies; the pixels must not."""
        stego = str(tmp_path / "stego.png")
        image_stego.embed_image(png_cover, stego, PAYLOAD, 2, 0)
        array, _ = image_io.load_image(stego)

        import io

        from PIL import Image

        for level in DEFLATE_LEVELS:
            data = size_preservation.encode_png_at_level(array, level)
            decoded = Image.open(io.BytesIO(data))
            assert (
                __import__("numpy").asarray(decoded).reshape(array.shape) == array
            ).all(), level

    def test_the_levels_produce_a_range_of_sizes_for_compressible_content(
        self, flat_png_cover, tmp_path
    ):
        """Otherwise step 1 of the strategy would be pointless."""
        stego = str(tmp_path / "stego.png")
        image_stego.embed_image(flat_png_cover, stego, PAYLOAD, 2, 0)
        array, _ = image_io.load_image(stego)

        sizes = {
            len(size_preservation.encode_png_at_level(array, level))
            for level in DEFLATE_LEVELS
        }
        assert len(sizes) > 1

    def test_the_levels_all_agree_for_incompressible_content(
        self, noisy_png_cover, tmp_path
    ):
        """A measured limit of step 1, not a bug.

        Noise cannot be compressed, so zlib emits stored blocks at every level and all
        ten candidates come out the same length. For such a file the level sweep offers
        no choice at all — and does not need to, because the stego file is already the
        cover's size for the same reason.
        """
        stego = str(tmp_path / "stego.png")
        image_stego.embed_image(noisy_png_cover, stego, PAYLOAD, 2, 0)
        array, _ = image_io.load_image(stego)

        sizes = {
            len(size_preservation.encode_png_at_level(array, level))
            for level in DEFLATE_LEVELS
        }
        assert len(sizes) == 1
        assert os.path.getsize(stego) == os.path.getsize(noisy_png_cover)

    def test_an_invalid_level_is_refused(self, png_cover):
        array, _ = image_io.load_image(png_cover)
        with pytest.raises(ValidationError, match="DEFLATE level"):
            size_preservation.encode_png_at_level(array, 11)


class TestPadding:
    def test_padding_reaches_the_target_exactly(self, png_cover):
        raw = Path(png_cover).read_bytes()
        target = len(raw) + 100

        padded = size_preservation.pad_png_to_size(raw, target)
        assert len(padded) == target

    def test_padding_leaves_the_pixels_identical(self, png_cover, tmp_path):
        raw = Path(png_cover).read_bytes()
        padded = size_preservation.pad_png_to_size(raw, len(raw) + 500)

        target = tmp_path / "padded.png"
        target.write_bytes(padded)

        before, _ = image_io.load_image(png_cover)
        after, _ = image_io.load_image(str(target))
        assert (before == after).all()

    def test_the_padding_chunk_is_ancillary_and_private(self):
        """Both letters matter: ancillary means skippable, private means no clash."""
        assert PADDING_CHUNK_TYPE[0:1].islower()  # ancillary
        assert PADDING_CHUNK_TYPE[1:2].islower()  # private

    def test_padding_to_the_same_size_is_a_no_op(self, png_cover):
        raw = Path(png_cover).read_bytes()
        assert size_preservation.pad_png_to_size(raw, len(raw)) == raw

    def test_shrinking_is_refused_with_a_reason(self, png_cover):
        raw = Path(png_cover).read_bytes()
        with pytest.raises(ValidationError, match="cannot be shortened"):
            size_preservation.pad_png_to_size(raw, len(raw) - 100)

    def test_a_gap_smaller_than_a_chunk_is_refused(self, png_cover):
        raw = Path(png_cover).read_bytes()
        with pytest.raises(ValidationError, match="chunk costs"):
            size_preservation.pad_png_to_size(raw, len(raw) + 5)

    def test_a_non_png_is_refused(self):
        with pytest.raises(Exception):
            size_preservation.pad_png_to_size(b"not a png at all", 500)


class TestPngPreservationAttempt:
    #: The one combination measured to reach the padding branch: a two-value cover at
    #: depth 8. Replacing whole low bytes with payload bytes makes the pixel data
    #: *more* compressible than the cover's, so the best candidate lands under the
    #: target and the shortfall can be closed. Found by sweeping the patterns and
    #: depths, not assumed.
    PADDING_CASE_DEPTH = 8

    def test_the_strategy_matches_by_padding_where_measurement_says_it_can(
        self, extremes_png_cover, tmp_path
    ):
        """The success case, on the one combination measured to produce it.

        Not a general claim. What is asserted is that *when* the strategy reports a
        match, the file really is the cover's length to the byte and really does decode
        to the same pixels — the part that must never be wrong.
        """
        depth = self.PADDING_CASE_DEPTH
        stego = str(tmp_path / "stego.png")
        image_stego.embed_image(extremes_png_cover, stego, PAYLOAD, depth, 0)
        output = str(tmp_path / "matched.png")

        result = size_preservation.preserve_png_size(
            extremes_png_cover, stego, output
        )

        assert result.attempted is True
        assert result.exact is True
        assert os.path.getsize(output) == os.path.getsize(extremes_png_cover)
        assert result.content_unchanged is True
        assert result.details["padded_bytes"] > 0

    def test_the_matched_file_is_still_a_readable_png(
        self, extremes_png_cover, tmp_path
    ):
        """A padded file the application could not read back would be useless."""
        depth = self.PADDING_CASE_DEPTH
        stego = str(tmp_path / "stego.png")
        image_stego.embed_image(extremes_png_cover, stego, PAYLOAD, depth, 0)
        output = str(tmp_path / "matched.png")
        size_preservation.preserve_png_size(extremes_png_cover, stego, output)

        before, _ = image_io.load_image(stego)
        after, _ = image_io.load_image(output)
        assert (before == after).all()

    def test_the_payload_still_extracts_from_the_matched_file(
        self, extremes_png_cover, tmp_path
    ):
        """The whole point: matching the size must not cost the payload."""
        depth = self.PADDING_CASE_DEPTH
        stego = str(tmp_path / "stego.png")
        image_stego.embed_image(extremes_png_cover, stego, PAYLOAD, depth, 0)
        output = str(tmp_path / "matched.png")
        size_preservation.preserve_png_size(extremes_png_cover, stego, output)

        assert image_stego.extract_image(output, depth, 0) == PAYLOAD

    def test_a_level_sweep_alone_can_match_an_incompressible_cover(
        self, noisy_png_cover, tmp_path
    ):
        """Step 1 on its own, with no padding involved.

        A noise cover is stored rather than compressed, so one of the ten candidates
        equals the cover's length exactly and nothing has to be appended. This is the
        cleanest outcome available: exact size, no unusual chunk, no trace.
        """
        stego = str(tmp_path / "stego.png")
        image_stego.embed_image(noisy_png_cover, stego, PAYLOAD, 8, 0)

        result = size_preservation.preserve_png_size(
            noisy_png_cover, stego, str(tmp_path / "matched.png")
        )
        record(result, "PNG (noise cover), depth 8, attempt")

        assert result.exact is True
        assert result.details["padded_bytes"] == 0
        assert result.details["exact_level"] is not None
        assert "re-encoding at DEFLATE level" in result.strategy

    def test_a_noise_cover_needs_no_help_at_all(self, noisy_png_cover, tmp_path):
        """Free preservation, recorded because it is the cheapest outcome available."""
        stego = str(tmp_path / "stego.png")
        image_stego.embed_image(noisy_png_cover, stego, PAYLOAD, 2, 0)

        baseline = size_preservation.size_outcome(noisy_png_cover, stego)
        record(baseline, "PNG (noise cover), depth 2, baseline")

        assert baseline.exact is True
        assert baseline.attempted is False

    def test_an_impossible_case_is_reported_rather_than_forced(
        self, flat_png_cover, tmp_path
    ):
        """A flat cover compresses to nothing, so the stego version cannot shrink to it."""
        stego = str(tmp_path / "stego.png")
        image_stego.embed_image(flat_png_cover, stego, PAYLOAD, 8, 0)

        result = size_preservation.preserve_png_size(
            flat_png_cover, stego, str(tmp_path / "attempted.png")
        )
        record(result, "PNG (flat cover), depth 8, attempt")

        assert result.exact is False
        assert "not matched" in result.strategy
        assert any("cannot be removed" in note for note in result.notes)
        # And the pixels still survived the attempt.
        assert result.content_unchanged is True

    def test_the_attempt_records_every_level_it_tried(self, png_cover, tmp_path):
        stego = str(tmp_path / "stego.png")
        image_stego.embed_image(png_cover, stego, PAYLOAD, 2, 0)

        result = size_preservation.preserve_png_size(
            png_cover, stego, str(tmp_path / "out.png")
        )
        assert set(result.details["sizes_by_deflate_level"]) == set(DEFLATE_LEVELS)

    def test_padding_is_disclosed_when_it_was_used(
        self, extremes_png_cover, tmp_path
    ):
        """Silently padding a file to look right would be the dishonest option."""
        stego = str(tmp_path / "stego.png")
        image_stego.embed_image(
            extremes_png_cover, stego, PAYLOAD, self.PADDING_CASE_DEPTH, 0
        )

        result = size_preservation.preserve_png_size(
            extremes_png_cover, stego, str(tmp_path / "out.png")
        )
        assert result.details["padded_bytes"] > 0
        assert any("conspicuous" in note for note in result.notes)
        assert "padding chunk" in result.strategy

    def test_a_bmp_is_refused_by_the_png_experiment(self, bmp_cover, tmp_path):
        stego = str(tmp_path / "stego.bmp")
        image_stego.embed_image(bmp_cover, stego, PAYLOAD, 2, 0)

        with pytest.raises(ValidationError, match="applies to PNG"):
            size_preservation.preserve_png_size(
                bmp_cover, stego, str(tmp_path / "out.bmp")
            )

    @pytest.mark.parametrize("depth", [1, 2, 4, 8])
    def test_the_outcome_is_recorded_across_depths(
        self, extremes_png_cover, tmp_path, depth
    ):
        """The sweep the evidence table reports.

        No particular outcome is asserted, because the answer legitimately depends on
        the depth: more bits replaced means less compressible pixel data, so a match
        that is available at depth 1 may not be at depth 8. What is asserted is that
        every outcome is lossless and explains itself.
        """
        stego = str(tmp_path / f"stego{depth}.png")
        image_stego.embed_image(extremes_png_cover, stego, PAYLOAD, depth, 0)

        result = size_preservation.preserve_png_size(
            extremes_png_cover, stego, str(tmp_path / f"out{depth}.png")
        )
        record(result, f"PNG (two-value cover), depth {depth}, attempt")

        assert result.content_unchanged is True
        assert result.notes


