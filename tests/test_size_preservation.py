class TestThroughProtect:
    """The option as a user meets it, including the part that could go wrong.

    Rewriting the stego file after embedding is only safe if the manifest is written
    afterwards, because the manifest records the file's digest. That ordering is the
    thing most worth a test here: getting it wrong would produce a manifest describing
    a file that no longer exists, and the symptom would appear much later.
    """

    @pytest.fixture(scope="class")
    def keys(self):
        from app.crypto import key_manager

        return key_manager.generate_key_pair(constants.RSA_MIN_KEY_SIZE)

    def _protect(self, cover, tmp_path, keys, *, match, depth=2, name="stego"):
        from app.crypto import key_manager
        from app.crypto.encryption import MIN_SCRYPT_N
        from app.verification.protect import protect_media

        private_key, public_key = keys
        public_path = str(tmp_path / "public.pem")
        key_manager.save_public_key(public_key, public_path, overwrite=True)

        extension = os.path.splitext(cover)[1]
        result = protect_media(
            cover,
            str(tmp_path / f"{name}{extension}"),
            b"A short protected message.",
            private_key,
            media_id="SIZE-001",
            lsb_depth=depth,
            start_secret="the start secret",
            match_cover_size=match,
            scrypt_n=MIN_SCRYPT_N,
            scrypt_r=8,
            scrypt_p=1,
        )
        return result, public_path

    def test_the_option_is_off_by_default(self, png_cover, tmp_path, keys):
        result, _ = self._protect(png_cover, tmp_path, keys, match=False)
        assert result.size_preservation is None

    def test_the_outcome_is_reported_when_the_option_is_on(
        self, png_cover, tmp_path, keys
    ):
        result, _ = self._protect(png_cover, tmp_path, keys, match=True)

        assert result.size_preservation is not None
        assert result.size_preservation.notes

    def test_the_manifest_digest_matches_the_rewritten_file(
        self, noisy_png_cover, tmp_path, keys
    ):
        """The ordering test. A stale digest here would be a real bug.

        The noise cover is used because it reliably *does* get rewritten and matched,
        so the digest genuinely has to have been taken afterwards for this to pass.
        """
        result, _ = self._protect(noisy_png_cover, tmp_path, keys, match=True, depth=8)

        assert result.size_preservation.exact is True
        assert result.manifest.stego_sha256 == file_utils.file_sha256(
            result.stego_path
        )

    def test_the_rewritten_file_still_verifies(
        self, noisy_png_cover, tmp_path, keys
    ):
        """Matching the size must not cost the verdict."""
        from app.verification import verdicts
        from app.verification.verifier import verify_media

        result, public_path = self._protect(
            noisy_png_cover, tmp_path, keys, match=True, depth=8
        )
        assert result.size_preservation.exact is True
        assert os.path.getsize(result.stego_path) == os.path.getsize(noisy_png_cover)

        outcome = verify_media(
            result.stego_path,
            result.manifest_path,
            public_path,
            start_secret="the start secret",
        )
        assert outcome.verdict == verdicts.VERDICT_AUTHENTIC

    def test_a_failure_to_match_does_not_stop_the_protect(
        self, flat_png_cover, tmp_path, keys
    ):
        """The size is a nice-to-have; refusing to protect over it would be absurd."""
