"""The file-size preservation experiment, and the evidence it produces.

The project plan asks for this to be investigated and the outcome recorded, and
warns specifically against claiming exact preservation works in general unless
testing shows it. So this file is written to *find out*, and its assertions are
about the mechanism rather than about a hoped-for answer:

* WAV and BMP are asserted to preserve size exactly, because that follows from how
  they store samples and a failure would be a bug in the writer.
* PNG is **not** asserted to be matchable. What is asserted is that when the
  experiment reports a match the file really is byte-for-byte the right length and
  still decodes to the same pixels, and that when it reports a failure it explains
  why. Both outcomes are exercised deliberately.
* Video is asserted only to be reported as not applicable, since a protected clip is
  a full re-encode.

The results are written to ``evidence/results/size_preservation.{json,md}`` so the
submission has the record the plan asks for.
"""

