class TestInherentPreservation:
    def test_wav_preserves_size_exactly(self, wav_cover, tmp_path):
        stego = str(tmp_path / "stego.wav")
        audio_stego.embed_audio(wav_cover, stego, PAYLOAD, 2, 0)

        result = size_preservation.size_outcome(wav_cover, stego)
        record(result, "WAV, depth 2")

        assert result.exact is True
        assert result.inherent is True
        assert result.difference == 0

    @pytest.mark.parametrize("depth", [1, 4, 8])
    def test_wav_preserves_size_at_every_depth(self, wav_cover, tmp_path, depth):
        """Depth cannot matter here, and asserting that is the point."""
        stego = str(tmp_path / f"stego{depth}.wav")
        audio_stego.embed_audio(wav_cover, stego, PAYLOAD, depth, 0)

        assert os.path.getsize(stego) == os.path.getsize(wav_cover)

    def test_bmp_preserves_size_exactly(self, bmp_cover, tmp_path):
        stego = str(tmp_path / "stego.bmp")
        image_stego.embed_image(bmp_cover, stego, PAYLOAD, 3, 0)

        result = size_preservation.size_outcome(bmp_cover, stego)
        record(result, "BMP, depth 3")

        assert result.exact is True
        assert result.inherent is True

    @pytest.mark.parametrize("depth", [1, 4, 8])
    def test_bmp_preserves_size_at_every_depth(self, bmp_cover, tmp_path, depth):
        stego = str(tmp_path / f"stego{depth}.bmp")
        image_stego.embed_image(bmp_cover, stego, PAYLOAD, depth, 0)

        assert os.path.getsize(stego) == os.path.getsize(bmp_cover)

    def test_the_reason_is_recorded_not_just_the_result(self, wav_cover, tmp_path):
        stego = str(tmp_path / "stego.wav")
