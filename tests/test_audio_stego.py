class TestRoundTrip:
    @pytest.mark.parametrize("lsb_count", range(1, 9))
    def test_every_depth_round_trips(self, tmp_path, lsb_count):
        """Also the case the committed round-trip evidence is generated from."""
        frames = 44_100
        cover = write_audio_file(str(tmp_path), make_audio(frames))
        stego = str(tmp_path / f"stego_{lsb_count}.wav")

        result = audio_stego.embed_audio(cover, stego, PAYLOAD, lsb_count, 100)
        recovered = audio_stego.extract_audio(stego, lsb_count, 100)

        original_samples, _ = audio_stego.read_audio(cover)
        stego_samples, _ = audio_stego.read_audio(stego)
        largest = int(
            np.abs(
                stego_samples.astype(np.int32) - original_samples.astype(np.int32)
            ).max(initial=0)
        )
        bound = (1 << lsb_count) - 1

        _ROUND_TRIP.append(
            {
                "lsb_depth": lsb_count,
                "cover_frames": frames,
                "start_location": 100,
                "payload_length": len(PAYLOAD),
                "samples_written": result.samples_written,
                "max_sample_change": largest,
                "distortion_bound": bound,
                "payload_recovered": recovered == PAYLOAD,
                "passed": recovered == PAYLOAD and largest <= bound,
            }
        )

        assert recovered == PAYLOAD
        assert largest <= bound
        # The cover must be left alone on disk, not merely in memory.
        assert Path(cover).exists()

    @given(audio_case())
    @settings(max_examples=40)
    def test_extract_returns_the_embedded_payload(self, case):
        with ScratchDirectory() as directory:
            cover = write_case(directory, case)
            stego = os.path.join(directory, "stego.wav")

            audio_stego.embed_audio(
                cover,
                stego,
                case["payload"],
                case["lsb_count"],
                case["start_location"],
            )
            recovered = audio_stego.extract_audio(
                stego, case["lsb_count"], case["start_location"]
            )
            assert recovered == case["payload"]

    def test_stereo_round_trips(self, tmp_path):
        cover = write_audio_file(str(tmp_path), make_audio(8_000, channels=2))
        stego = str(tmp_path / "stego.wav")

        audio_stego.embed_audio(cover, stego, PAYLOAD, 2, 7)
        assert audio_stego.extract_audio(stego, 2, 7) == PAYLOAD

    def test_empty_payload_round_trips(self, tmp_path):
        cover = write_audio_file(str(tmp_path), make_audio(1_000))
        stego = str(tmp_path / "stego.wav")

        audio_stego.embed_audio(cover, stego, b"", 1, 0)
        assert audio_stego.extract_audio(stego, 1, 0) == b""

