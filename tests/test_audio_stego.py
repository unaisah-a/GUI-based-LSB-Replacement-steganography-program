class TestFileErrors:
    def test_missing_input(self, tmp_path):
        with pytest.raises(FileError, match="not found"):
            audio_stego.embed_audio(
                str(tmp_path / "absent.wav"), str(tmp_path / "out.wav"), PAYLOAD, 1, 0
            )

    def test_input_is_a_directory(self, tmp_path):
        with pytest.raises(FileError, match="directory"):
            audio_stego.embed_audio(
                str(tmp_path), str(tmp_path / "out.wav"), PAYLOAD, 1, 0
            )

    def test_embedding_in_place_is_refused(self, tmp_path):
        """Embedding in place would destroy the cover object."""
        cover = write_audio_file(str(tmp_path), make_audio(4_000))
        with pytest.raises(ValidationError, match="must differ"):
            audio_stego.embed_audio(cover, cover, PAYLOAD, 1, 0)

    def test_the_cover_survives_a_refused_in_place_write(self, tmp_path):
        cover = write_audio_file(str(tmp_path), make_audio(4_000))
        before = Path(cover).read_bytes()

        with pytest.raises(ValidationError):
            audio_stego.embed_audio(cover, cover, PAYLOAD, 1, 0)
        assert Path(cover).read_bytes() == before

    def test_occupied_output_is_refused(self, tmp_path):
        """An existing file is never silently overwritten."""
        cover = write_audio_file(str(tmp_path), make_audio(4_000))
        stego = tmp_path / "stego.wav"
        stego.write_bytes(b"existing content")

        with pytest.raises(FileError, match="already occupied"):
            audio_stego.embed_audio(cover, str(stego), PAYLOAD, 1, 0)
        assert stego.read_bytes() == b"existing content"

    def test_overwrite_allows_replacement(self, tmp_path):
        cover = write_audio_file(str(tmp_path), make_audio(4_000))
        stego = tmp_path / "stego.wav"
        stego.write_bytes(b"existing content")

        audio_stego.embed_audio(cover, str(stego), PAYLOAD, 1, 0, overwrite=True)
        assert audio_stego.extract_audio(str(stego), 1, 0) == PAYLOAD

    def test_missing_output_directory(self, tmp_path):
        cover = write_audio_file(str(tmp_path), make_audio(1_000))
        with pytest.raises(FileError, match="output directory"):
            audio_stego.embed_audio(
                cover, str(tmp_path / "absent" / "out.wav"), PAYLOAD, 1, 0
            )

    def test_no_temporary_files_remain_after_a_successful_embed(self, tmp_path):
        cover = write_audio_file(str(tmp_path), make_audio(1_000))
        audio_stego.embed_audio(cover, str(tmp_path / "stego.wav"), PAYLOAD, 1, 0)

        names = sorted(entry.name for entry in tmp_path.iterdir())
        assert names == ["cover.wav", "stego.wav"]


