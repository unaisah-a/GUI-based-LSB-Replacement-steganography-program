class TestCapacity:
    def test_capacity_counts_every_channel(self, tmp_path):
        """Unlike an image's alpha channel, no audio channel is excluded."""
        mono = write_audio_file(str(tmp_path), make_audio(1_000), "mono")
        stereo = write_audio_file(
            str(tmp_path), make_audio(1_000, channels=2), "stereo"
        )

        mono_report, _ = audio_stego.measure_capacity(mono, 1)
        stereo_report, _ = audio_stego.measure_capacity(stereo, 1)

        assert stereo_report.total_embeddable_samples == (
            2 * mono_report.total_embeddable_samples
        )

    def test_capacity_grows_with_depth(self, tmp_path):
        cover = write_audio_file(str(tmp_path), make_audio(1_000))
        capacities = [
            audio_stego.measure_capacity(cover, depth)[0].available_capacity_bytes
            for depth in range(1, 9)
        ]
        assert capacities == sorted(capacities)

    def test_measuring_does_not_raise_for_an_oversized_payload(self, tmp_path):
        cover = write_audio_file(str(tmp_path), make_audio(100))
        report, _ = audio_stego.measure_capacity(cover, 1, 0, payload_length=10**6)
        assert report.payload_fits is False

    def test_descriptor_reports_the_media_properties(self, tmp_path):
        cover = write_audio_file(str(tmp_path), make_audio(4_410, channels=2))
        _, descriptor = audio_stego.measure_capacity(cover, 1)

        assert descriptor.sample_rate == AUDIO_SAMPLE_RATE
        assert descriptor.channel_count == 2
        assert descriptor.frame_count == 4_410
        assert descriptor.total_samples == 8_820
        assert descriptor.duration_seconds == pytest.approx(0.1)
        assert descriptor.subtype == audio_stego.SUPPORTED_SUBTYPE

    def test_payload_one_byte_over_capacity_is_refused(self, tmp_path):
        cover = write_audio_file(str(tmp_path), make_audio(500))
        report, _ = audio_stego.measure_capacity(cover, 1, 0)
        oversized = bytes(report.max_payload_length + 1)

        with pytest.raises(CapacityError, match="does not fit"):
            audio_stego.embed_audio(
                cover, str(tmp_path / "stego.wav"), oversized, 1, 0
            )

    def test_no_output_file_is_left_after_a_capacity_failure(self, tmp_path):
        cover = write_audio_file(str(tmp_path), make_audio(200))
        stego = str(tmp_path / "stego.wav")

        with pytest.raises(CapacityError):
            audio_stego.embed_audio(cover, stego, bytes(10_000), 1, 0)
        assert not os.path.exists(stego)

    def test_start_location_reduces_capacity(self, tmp_path):
        cover = write_audio_file(str(tmp_path), make_audio(1_000))
        near, _ = audio_stego.measure_capacity(cover, 1, 0)
        far, _ = audio_stego.measure_capacity(cover, 1, 500)
        assert far.available_capacity_bytes < near.available_capacity_bytes


