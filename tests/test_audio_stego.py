class TestCoverPreservation:
    @given(audio_case())
    @settings(max_examples=30)
    def test_bits_above_the_depth_are_unchanged(self, case):
        with ScratchDirectory() as directory:
            cover_path = write_case(directory, case)
            stego_path = os.path.join(directory, "stego.wav")
            audio_stego.embed_audio(
                cover_path,
                stego_path,
                case["payload"],
                case["lsb_count"],
                case["start_location"],
            )

            before, _ = audio_stego.read_audio(cover_path)
            after, _ = audio_stego.read_audio(stego_path)
            keep = np.uint16(0xFFFF ^ ((1 << case["lsb_count"]) - 1))

            assert np.array_equal(
                before.reshape(-1).view(np.uint16) & keep,
                after.reshape(-1).view(np.uint16) & keep,
            )

    @given(audio_case())
    @settings(max_examples=30)
    def test_samples_outside_the_written_range_are_identical(self, case):
        with ScratchDirectory() as directory:
            cover_path = write_case(directory, case)
            stego_path = os.path.join(directory, "stego.wav")
            result = audio_stego.embed_audio(
                cover_path,
                stego_path,
                case["payload"],
                case["lsb_count"],
                case["start_location"],
            )

            before, _ = audio_stego.read_audio(cover_path)
            after, _ = audio_stego.read_audio(stego_path)
            flat_before = before.reshape(-1)
            flat_after = after.reshape(-1)
            start = result.start_location
            end = start + result.samples_written

            assert np.array_equal(flat_before[:start], flat_after[:start])
            assert np.array_equal(flat_before[end:], flat_after[end:])

    @given(audio_case())
    @settings(max_examples=30)
    def test_per_sample_change_is_bounded_by_the_depth(self, case):
        with ScratchDirectory() as directory:
            cover_path = write_case(directory, case)
            stego_path = os.path.join(directory, "stego.wav")
            audio_stego.embed_audio(
                cover_path,
                stego_path,
                case["payload"],
                case["lsb_count"],
                case["start_location"],
            )

            before, _ = audio_stego.read_audio(cover_path)
            after, _ = audio_stego.read_audio(stego_path)
            difference = np.abs(
                before.astype(np.int64) - after.astype(np.int64)
            )
            assert difference.max(initial=0) < (1 << case["lsb_count"])

    def test_the_cover_file_is_left_byte_for_byte_unchanged(self, tmp_path):
        cover = write_audio_file(str(tmp_path), make_audio(4_000))
        before = Path(cover).read_bytes()

        audio_stego.embed_audio(cover, str(tmp_path / "stego.wav"), PAYLOAD, 4, 0)
        assert Path(cover).read_bytes() == before

    def test_media_properties_are_preserved(self, tmp_path):
        cover = write_audio_file(str(tmp_path), make_audio(4_000, channels=2))
        stego = str(tmp_path / "stego.wav")
        audio_stego.embed_audio(cover, stego, PAYLOAD, 4, 0)

        original = audio_stego.describe_only(cover)
        written = audio_stego.describe_only(stego)

        assert written.sample_rate == original.sample_rate
        assert written.channel_count == original.channel_count
        assert written.frame_count == original.frame_count
        assert written.subtype == original.subtype

    def test_wav_output_preserves_the_file_size(self, tmp_path):
        """PCM replaces sample bytes in place, so the size should not move."""
        cover = write_audio_file(str(tmp_path), make_audio(4_000))
        stego = str(tmp_path / "stego.wav")
        audio_stego.embed_audio(cover, stego, PAYLOAD, 4, 0)

        assert os.path.getsize(stego) == os.path.getsize(cover)


