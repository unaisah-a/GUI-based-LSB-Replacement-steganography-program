class TestRemovedInterface:
    """The superseded names and behaviours must not come back.

    Each was a concrete interoperability problem; see the module docstring of
    ``app/stego/audio_stego.py``.
    """

    def test_old_embed_name_is_gone(self):
        assert not hasattr(audio_stego, "embed_audio_lsb")

    def test_old_extract_name_is_gone(self):
        assert not hasattr(audio_stego, "extract_audio_lsb")

    def test_the_private_magic_marker_is_gone(self):
        assert not hasattr(audio_stego, "MAGIC")

    def test_the_passcode_parameter_is_gone(self):
        """Key-derived behaviour belongs in the cryptography layer."""
        import inspect

        assert "passcode" not in inspect.signature(audio_stego.embed_audio).parameters
        assert "passcode" not in inspect.signature(audio_stego.extract_audio).parameters

    def test_the_layer_imports_nothing_from_the_crypto_package(self):
        """Checked against the parsed imports, not the raw text.

        The module docstring mentions ``app.crypto.envelope`` when explaining
        where the payload marker moved to, so a substring search over the source
        would match prose rather than an import.
        """
        import ast
        import inspect

        tree = ast.parse(inspect.getsource(audio_stego))
        imported: list[str] = []
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                imported.extend(alias.name for alias in node.names)
            elif isinstance(node, ast.ImportFrom) and node.module:
                imported.append(node.module)

        assert not [name for name in imported if name.startswith("app.crypto")]

    def test_the_shared_bit_helpers_are_actually_used(self):
        import inspect

        source = inspect.getsource(audio_stego)
        assert "from app.stego.bit_utils import" in source

    def test_no_private_bit_conversion_helpers_remain(self):
        """These duplicated bit_utils with different error types."""
        assert not hasattr(audio_stego, "bytes_to_bits") or (
            audio_stego.bytes_to_bits is bit_utils.bytes_to_bits
        )
        assert not hasattr(audio_stego, "build_packet")
        assert not hasattr(audio_stego, "parse_packet")
        assert not hasattr(audio_stego, "_iter_lsb_bits")


