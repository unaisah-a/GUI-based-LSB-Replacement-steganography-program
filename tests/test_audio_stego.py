#
# Values are derived from earlier draws rather than filtered, exactly as
# conftest.embedding_case does for images, so Hypothesis never rejects an example.


@st.composite
def audio_case(draw):
    channels = draw(st.sampled_from((1, 2)))
    lsb_count = draw(st.integers(min_value=1, max_value=8))
    pattern = draw(st.sampled_from(("tone", "noise", "silence", "extremes", "ramp")))
    seed = draw(st.integers(min_value=0, max_value=2**32 - 1))

    header_samples = math.ceil(capacity.LENGTH_HEADER_BYTES * 8 / lsb_count)
    lowest_frames = max(1, math.ceil(header_samples / channels))
    frame_count = draw(st.integers(min_value=lowest_frames, max_value=2_048))

    total_samples = frame_count * channels
    room = (total_samples * lsb_count) // 8
    payload_ceiling = max(0, room - capacity.LENGTH_HEADER_BYTES)
    payload_length = draw(st.integers(min_value=0, max_value=min(256, payload_ceiling)))
    payload = draw(st.binary(min_size=payload_length, max_size=payload_length))

    needed = math.ceil(
        (payload_length + capacity.LENGTH_HEADER_BYTES) * 8 / lsb_count
    )
    highest_start = max(0, total_samples - needed)
    start_location = draw(st.integers(min_value=0, max_value=highest_start))

    return {
        "channels": channels,
        "lsb_count": lsb_count,
        "pattern": pattern,
        "seed": seed,
        "frame_count": frame_count,
        "payload": payload,
        "start_location": start_location,
    }


def write_case(directory: str, case: dict, name: str = "cover") -> str:
    samples = make_audio(
        case["frame_count"], case["channels"], case["pattern"], case["seed"]
    )
    return write_audio_file(directory, samples, name)


