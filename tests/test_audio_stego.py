class TestCrossMediaParity:
    """Both media must behave identically wherever they can.

    This is the class that would have caught the original divergence, and the one
    the media facade in ``app/stego/media.py`` relies on.
    """

    def test_the_agreed_positional_signature_works_for_both(self, tmp_path):
        image_cover = write_cover(
            str(tmp_path), make_cover(64, 64, 3), image_io.PNG, "cover"
        )
        audio_cover = write_audio_file(str(tmp_path), make_audio(8_000))

        image_stego.embed_image(
            image_cover, str(tmp_path / "s.png"), PAYLOAD, 3, 100
        )
        audio_stego.embed_audio(
            audio_cover, str(tmp_path / "s.wav"), PAYLOAD, 3, 100
        )

        assert image_stego.extract_image(str(tmp_path / "s.png"), 3, 100) == PAYLOAD
        assert audio_stego.extract_audio(str(tmp_path / "s.wav"), 3, 100) == PAYLOAD

    def test_the_shared_stream_has_a_32_bit_length_header(self):
        from app.stego import lsb_core

        assert lsb_core.LENGTH_HEADER_BITS == 32

    def test_both_layers_report_a_capacity_report(self, tmp_path):
        image_cover = write_cover(
            str(tmp_path), make_cover(32, 32, 3), image_io.PNG, "cover"
        )
        audio_cover = write_audio_file(str(tmp_path), make_audio(8_000))

        image_report, _ = image_stego.measure_capacity(image_cover, 4)
        audio_report, _ = audio_stego.measure_capacity(audio_cover, 4)

        assert isinstance(image_report, capacity.CapacityReport)
        assert isinstance(audio_report, capacity.CapacityReport)

    def test_one_handler_catches_errors_from_both_layers(self, tmp_path):
        """The old audio layer raised bare ValueError, which this would miss."""
        image_cover = write_cover(
            str(tmp_path), make_cover(8, 8, 3), image_io.PNG, "cover"
        )
        audio_cover = write_audio_file(str(tmp_path), make_audio(1_000))

        for call in (
            lambda: image_stego.embed_image(
                image_cover, str(tmp_path / "a.png"), PAYLOAD, 99, 0
            ),
            lambda: audio_stego.embed_audio(
                audio_cover, str(tmp_path / "a.wav"), PAYLOAD, 99, 0
            ),
        ):
            with pytest.raises(StegoError):
                call()

    @pytest.mark.parametrize("depth", range(1, 9))
    def test_identical_payloads_produce_identical_low_bits(self, tmp_path, depth):
        """The two media must agree on bit ordering, not merely round-trip."""
        payload = bytes(range(40))
        encoded = len(payload).to_bytes(4, "big") + payload
        expected = bit_utils.pack_bits_to_groups(
            bit_utils.bytes_to_bits(encoded), depth
        )

        image_cover = write_cover(
            str(tmp_path), make_cover(64, 64, 3), image_io.PNG, f"c{depth}"
        )
        audio_cover = write_audio_file(
            str(tmp_path), make_audio(8_000), f"a{depth}"
        )
        image_out = str(tmp_path / f"s{depth}.png")
        audio_out = str(tmp_path / f"s{depth}.wav")

        image_stego.embed_image(image_cover, image_out, payload, depth, 0)
        audio_stego.embed_audio(audio_cover, audio_out, payload, depth, 0)

        image_array, _ = image_io.load_image(image_out)
        image_flat, _ = image_stego.embeddable_stream(image_array)
        image_bits = bit_utils.read_low_bits(
            image_flat[: expected.size], depth, 8
        )

        audio_samples, _ = audio_stego.read_audio(audio_out)
        audio_flat, _ = audio_stego.embeddable_stream(audio_samples)
        audio_bits = bit_utils.read_low_bits(
            audio_flat[: expected.size], depth, 16
        )

        assert np.array_equal(image_bits.astype(np.uint16), expected)
        assert np.array_equal(audio_bits.astype(np.uint16), expected)

    def test_both_layers_expose_the_same_result_fields(self, tmp_path):
        image_cover = write_cover(
            str(tmp_path), make_cover(64, 64, 3), image_io.PNG, "cover"
        )
        audio_cover = write_audio_file(str(tmp_path), make_audio(8_000))

        image_result = image_stego.embed_image(
            image_cover, str(tmp_path / "s.png"), PAYLOAD, 3, 10
        )
        audio_result = audio_stego.embed_audio(
            audio_cover, str(tmp_path / "s.wav"), PAYLOAD, 3, 10
        )

        shared = {
            "output_path",
            "container_format",
            "descriptor",
            "capacity",
            "lsb_count",
            "start_location",
            "payload_length",
            "encoded_length",
            "samples_written",
        }
        assert shared <= set(vars(image_result))
        assert shared <= set(vars(audio_result))
        assert image_result.encoded_length == audio_result.encoded_length
        assert image_result.samples_written == audio_result.samples_written
