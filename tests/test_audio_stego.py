class TestExtractionErrors:
    def test_wrong_depth_does_not_raise_a_bare_exception(self, tmp_path):
        """Whatever happens, it must be a StegoError, not an IndexError."""
        cover = write_audio_file(str(tmp_path), make_audio(4_000))
        stego = str(tmp_path / "stego.wav")
        audio_stego.embed_audio(cover, stego, PAYLOAD, 1, 0)

        try:
            recovered = audio_stego.extract_audio(stego, 8, 0)
        except StegoError:
            pass
        else:
            # A mismatched read may decode a plausible length and return wrong
            # bytes with no error at all. That is expected and documented; what
            # matters is that it never silently equals the real payload.
            assert recovered != PAYLOAD

    def test_truncated_stream_is_reported(self, tmp_path):
        cover = write_audio_file(str(tmp_path), make_audio(40))
        with pytest.raises(ExtractionError, match="truncated"):
            audio_stego.extract_audio(cover, 1, 35)

    def test_manifest_length_disagreement_is_reported(self, tmp_path):
        cover = write_audio_file(str(tmp_path), make_audio(4_000))
        stego = str(tmp_path / "stego.wav")
        audio_stego.embed_audio(cover, stego, PAYLOAD, 2, 0)

        with pytest.raises(ExtractionError, match="disagrees with the manifest"):
            audio_stego.extract_audio(stego, 2, 0, manifest_payload_length=999)

    def test_matching_manifest_length_is_accepted(self, tmp_path):
        cover = write_audio_file(str(tmp_path), make_audio(4_000))
        stego = str(tmp_path / "stego.wav")
        audio_stego.embed_audio(cover, stego, PAYLOAD, 2, 0)

        assert (
            audio_stego.extract_audio(
                stego, 2, 0, manifest_payload_length=len(PAYLOAD)
            )
            == PAYLOAD
        )

    def test_extraction_messages_do_not_claim_a_cause(self, tmp_path):
        cover = write_audio_file(str(tmp_path), make_audio(40))
        with pytest.raises(ExtractionError) as caught:
            audio_stego.extract_audio(cover, 1, 35)

        message = str(caught.value).lower()
        for claim in ("wrong passcode", "wrong secret", "wrong start location"):
            assert claim not in message

    def test_missing_input_for_extraction(self, tmp_path):
        with pytest.raises(FileError, match="not found"):
            audio_stego.extract_audio(str(tmp_path / "absent.wav"), 1, 0)


